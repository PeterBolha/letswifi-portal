namespace letswifi\credential;

use DateTimeImmutable;
use DomainException;
use PDO;
use fyrkat\openssl\DN;
use fyrkat\openssl\X509;
use letswifi\auth\User;
use letswifi\profile\ProfileService;
use letswifi\profile\Realm;

/**
 * Issues certificates from a client-provided CSR.
 *
 * Unlike CertificateCredentialIssuer, the keypair is generated by the client;
 * the server only validates the request, builds the certificate content
 * itself, and signs it with the realm CA.  The issued certificate is logged
 * in realm_signing_log exactly as in the classic flow (usage "client"), with
 * source "csr" marking how the keypair was created, so requester listing,
 * revocation, and CRL generation work unchanged.
 *
 * @internal
 */
class CsrCredentialIssuer
{
	public const DATE_FORMAT = CertificateCredentialIssuer::DATE_FORMAT;

	/** Purpose of the issued certificate; same as in the classic flow */
	public const USAGE = 'client';

	/** How the keypair was created, recorded in realm_signing_log."source" */
	public const SOURCE = 'csr';

	/**
	 * Default per-requester cap on concurrently valid CSR-issued certificates;
	 * overridable per realm with the `csr_issuance_limit` extra.
	 */
	public const DEFAULT_ISSUANCE_LIMIT = 10;

	/**
	 * Extensions for the issued certificate; deliberately does NOT copy any
	 * extension requested in the CSR.  The -clrext flag in the signing key
	 * drops CSR-requested extensions before these are applied.
	 */
	public const EXTENSIONS = <<<CONF
		subjectKeyIdentifier   = hash
		authorityKeyIdentifier = keyid:always, issuer:always
		basicConstraints       = CA:FALSE
		keyUsage               = digitalSignature, nonRepudiation, keyEncipherment
		extendedKeyUsage       = clientAuth
		CONF;

	/** @param User $user the authenticated requester; identity never comes from the CSR */
	public function __construct(
		public readonly User $user,
		public readonly Realm $realm,
		public readonly DateTimeImmutable $now,
		private readonly ProfileService $profileService,
	) {
	}

	/**
	 * Validate, sign, and log a client CSR.
	 *
	 * @param string $csrPem validated PEM CSR, as returned by CsrValidator::validate()
	 */
	public function issueFromCsr( string $csrPem ): CsrCredential
	{
		$ident = Ident::generate( $this->realm->realmId );
		$this->checkIssuanceLimit();

		$notBefore = $this->now;
		$notAfter = $this->now->add( $this->realm->validity );
		$caCert = $this->realm->getSignerCertificate();
		$subject = new DN( ['CN' => $ident] );

		$serial = $this->logPreparedCredential( $caCert, $csrPem, $subject, $ident, $notBefore, $notAfter );

		$signingKey = $this->profileService->getSigningKey( $this->realm->signer );
		$userCert = $signingKey->sign(
			$csrPem,
			$subject,
			static::EXTENSIONS,
			$serial,
			$notBefore,
			$notAfter,
		);

		$this->logCompletedCredential( $userCert, $ident );

		return new CsrCredential(
			credentialId: $ident,
			userId: $this->user->userId,
			clientId: $this->user->clientId,
			grantSid: $this->user->grantSid,
			ip: $this->user->ip,
			userAgent: $this->user->userAgent,
			realm: $this->realm,
			userCert: $userCert,
			payload: [
				'x509' => $userCert->getX509Pem(),
				'chain' => \array_map(
					static fn( X509 $cert ): string => $cert->getX509Pem(),
					$this->profileService->getCertificatesWithChain( $userCert->getIssuerSubject()->__toString() ),
				),
			],
		);
	}

	/**
	 * Per-requester issuance limit, since the classic flow has no other cap
	 * and this endpoint is a direct signing path.
	 */
	private function checkIssuanceLimit(): void
	{
		$limit = $this->realm->getExtra( 'csr_issuance_limit' );
		$max = null === $limit ? self::DEFAULT_ISSUANCE_LIMIT : (int)$limit;
		$statement = $this->profileService->getPDO()->prepare( <<<SQL
			SELECT COUNT("serial")
			FROM "realm_signing_log"
			WHERE "realm" = :realm
				AND "requester" = :requester
				AND "source" = :source
				AND "revoked" IS NULL
				AND "expires" > :now
			SQL );
		$statement->bindValue( 'realm', $this->realm->realmId, PDO::PARAM_STR );
		$statement->bindValue( 'requester', $this->user->userId, PDO::PARAM_STR );
		$statement->bindValue( 'source', static::SOURCE, PDO::PARAM_STR );
		$statement->bindValue( 'now', \gmdate( static::DATE_FORMAT, $this->now->getTimestamp() ), PDO::PARAM_STR );
		$statement->execute();
		$count = (int)$statement->fetchColumn();
		if ( $count >= $max ) {
			throw new DomainException( "Issuance limit reached for realm {$this->realm->realmId}" );
		}
	}

	private function logPreparedCredential( X509 $caCert, string $csrPem, DN $subject, string $ident, DateTimeImmutable $issued, DateTimeImmutable $expires ): int
	{
		$pdo = $this->profileService->getPDO();
		$statement = $pdo->prepare( <<<SQL
			INSERT INTO "realm_signing_log"
				("realm", "requester", "ident", "grant", "ca_sub", "sub", "usage", "source", "issued", "expires", "csr", "client", "user_agent", "ip")
			VALUES
				(:realm, :requester, :ident, :grant, :ca_sub, :sub, :usage, :source, :issued, :expires, :csr, :client, :user_agent, :ip)
			SQL );
		$statement->bindValue( 'realm', $this->realm->realmId, PDO::PARAM_STR );
		$statement->bindValue( 'requester', $this->user->userId, PDO::PARAM_STR );
		$statement->bindValue( 'ident', $ident, PDO::PARAM_STR );
		$statement->bindValue( 'grant', $this->user->grantSid, PDO::PARAM_STR );
		$statement->bindValue( 'ca_sub', $caCert->getSubject(), PDO::PARAM_STR );
		$statement->bindValue( 'sub', $subject, PDO::PARAM_STR );
		$statement->bindValue( 'usage', static::USAGE, PDO::PARAM_STR );
		$statement->bindValue( 'source', static::SOURCE, PDO::PARAM_STR );
		$statement->bindValue( 'issued', \gmdate( static::DATE_FORMAT, $issued->getTimestamp() ), PDO::PARAM_STR );
		$statement->bindValue( 'expires', \gmdate( static::DATE_FORMAT, $expires->getTimestamp() ), PDO::PARAM_STR );
		$statement->bindValue( 'csr', $csrPem, PDO::PARAM_STR );
		$statement->bindValue( 'client', $this->user->clientId, PDO::PARAM_STR );
		$statement->bindValue( 'user_agent', $this->user->userAgent, PDO::PARAM_STR );
		$statement->bindValue( 'ip', $this->user->ip, PDO::PARAM_STR );
		$statement->execute();
		$last = $pdo->lastInsertId();
		$lastId = (int)$last;
		if ( 0 < $lastId && (string)$lastId === $last ) {
			return $lastId;
		}

		throw new DomainException( 'Unable to retrieve last insert ID from database' );
	}

	private function logCompletedCredential( X509 $userCert, string $ident ): void
	{
		$pdo = $this->profileService->getPDO();
		$statement = $pdo->prepare( <<<SQL
			UPDATE "realm_signing_log"
				SET
					"issued" = :issued,
					"expires" = :expires,
					"x509" = :x509
				WHERE
					"serial" = :serial
					AND "realm" = :realm
					AND "requester" = :requester
					AND "source" = :source
					AND "ca_sub" = :ca_sub
			SQL );
		$statement->bindValue( 'issued', \gmdate( static::DATE_FORMAT, $userCert->getValidFrom()->getTimestamp() ), PDO::PARAM_STR );
		$statement->bindValue( 'expires', \gmdate( static::DATE_FORMAT, $userCert->getValidTo()->getTimestamp() ), PDO::PARAM_STR );
		$statement->bindValue( 'x509', $userCert->getX509Pem(), PDO::PARAM_STR );
		$statement->bindValue( 'serial', $userCert->getSerialNumber(), PDO::PARAM_INT );
		$statement->bindValue( 'realm', $this->realm->realmId, PDO::PARAM_STR );
		$statement->bindValue( 'requester', $this->user->userId, PDO::PARAM_STR );
		$statement->bindValue( 'source', static::SOURCE, PDO::PARAM_STR );
		$statement->bindValue( 'ca_sub', $userCert->getIssuerSubject(), PDO::PARAM_STR );
		$statement->execute();
		$rows = $statement->rowCount();
		if ( 1 !== $rows ) {
			throw new DomainException( "Unable to log signed certificate; expected 1 rows to be updated but got {$rows}" );
		}
	}
}
